    @task(trigger_rule="none_failed_min_one_success")
    def purge_files(file_path: dict):
        """Removes extracted temporary CSV file (Equivalent to PurgeCurrentExecutionFiles)."""
        if os.path.exists(file_path):
                    os.remove(file_path)

