    @task(task_id="yellow_workflow.copy_and_merge")
    def bq_yellow_table_tmp_and_merge(meta: dict):
        client = bigquery.Client.from_service_account_json(KEY_PATH)
        gcp_project_id = Variable.get("GCP_PROJECT_ID")
        gcp_dataset = Variable.get("GCP_DATASET")
        table = meta['table']
        file_name = meta['file_name']
        sql_query=f"""
            CREATE OR REPLACE TABLE `{gcp_project_id}.{table}`AS
            SELECT
                MD5(CONCAT(
                    COALESCE(CAST(VendorID AS STRING), ""),
                    COALESCE(CAST(tpep_pickup_datetime AS STRING), ""),
                    COALESCE(CAST(tpep_dropoff_datetime AS STRING), ""),
                    COALESCE(CAST(PULocationID AS STRING), ""),
                    COALESCE(CAST(DOLocationID AS STRING), "")
                )) AS unique_row_id,
                "{file_name}" AS filename,
                *
            FROM `{gcp_project_id}.{table}_ext`;

            MERGE INTO `{gcp_project_id}.{gcp_dataset}.yellow_tripdata` T
            USING `{gcp_project_id}.{table}` S ON T.unique_row_id = S.unique_row_id
            WHEN NOT MATCHED THEN
                INSERT (unique_row_id, filename, VendorID, tpep_pickup_datetime, tpep_dropoff_datetime,
                        passenger_count, trip_distance, RatecodeID, store_and_fwd_flag, PULocationID,
                        DOLocationID, payment_type, fare_amount, extra, mta_tax, tip_amount, tolls_amount,
                        improvement_surcharge, total_amount, congestion_surcharge)
                VALUES (S.unique_row_id, S.filename, S.VendorID, S.tpep_pickup_datetime, S.tpep_dropoff_datetime,
                        S.passenger_count, S.trip_distance, S.RatecodeID, S.store_and_fwd_flag, S.PULocationID,
                        S.DOLocationID, S.payment_type, S.fare_amount, S.extra, S.mta_tax, S.tip_amount, S.tolls_amount,
                        S.improvement_surcharge, S.total_amount, S.congestion_surcharge);
        """
        client.query(sql_query).result()


